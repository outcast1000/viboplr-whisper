// Builds index.js — the one file the plugin loader evaluates — from align.js
// and plugin.js. align.js is wrapped so its exports land in a local
// `WhisperAlign` rather than on the worker's global scope.
//
//   node scripts/build.mjs          write index.js
//   node scripts/build.mjs --check  fail if index.js is not what a build writes
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => readFileSync(join(root, f), "utf8").replace(/\r\n/g, "\n");

const out = [
  "// GENERATED by scripts/build.mjs from align.js + plugin.js — edit those, not this.",
  "var WhisperAlign = (function () {",
  "  var module = { exports: {} };",
  read("align.js").trimEnd(),
  "  return module.exports;",
  "})();",
  "",
  read("plugin.js").trimEnd(),
  "",
  "return { activate: activate, deactivate: deactivate };",
  "",
].join("\n");

const target = join(root, "index.js");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("index.js is out of date — run: node scripts/build.mjs");
    process.exit(1);
  }
  console.log("index.js is up to date");
} else {
  writeFileSync(target, out);
  console.log("wrote index.js");
}
